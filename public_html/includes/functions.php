<?php

declare(strict_types=1);

if (session_status() !== PHP_SESSION_ACTIVE) {
    ini_set('session.use_strict_mode', '1');
    ini_set('session.cookie_httponly', '1');
    ini_set('session.cookie_samesite', 'Lax');
    if (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off') {
        ini_set('session.cookie_secure', '1');
    }
    session_start();
}

function e(?string $value): string
{
    return htmlspecialchars((string) $value, ENT_QUOTES, 'UTF-8');
}

function csrf_token(): string
{
    if (empty($_SESSION['csrf_token'])) {
        $_SESSION['csrf_token'] = bin2hex(random_bytes(32));
    }
    return $_SESSION['csrf_token'];
}

function is_active(string $page, string $currentPage): string
{
    return $page === $currentPage ? ' aria-current="page" class="active"' : '';
}

function clean_header_value(string $value): string
{
    return trim(preg_replace('/[\r\n]+/', ' ', $value) ?? '');
}

function clean_text(string $value, int $max = 4000): string
{
    $value = trim(strip_tags($value));
    $value = preg_replace('/\s{3,}/', "\n\n", $value) ?? $value;
    return function_exists('mb_substr') ? mb_substr($value, 0, $max) : substr($value, 0, $max);
}

function field(string $key): string
{
    return clean_text((string) ($_POST[$key] ?? ''));
}

function valid_csrf(): bool
{
    $token = (string) ($_POST['csrf_token'] ?? '');
    return $token !== '' && isset($_SESSION['csrf_token']) && hash_equals($_SESSION['csrf_token'], $token);
}

function rate_limit_ok(int $seconds = 12): bool
{
    $now = time();
    $last = (int) ($_SESSION['last_form_submission'] ?? 0);
    if ($last && ($now - $last) < $seconds) {
        return false;
    }
    $_SESSION['last_form_submission'] = $now;
    return true;
}

function mail_headers(?string $replyTo = null): string
{
    $headers = [
        'MIME-Version: 1.0',
        'Content-Type: text/html; charset=UTF-8',
        'Content-Transfer-Encoding: base64',
        'From: ' . clean_header_value(MAIL_FROM_NAME) . ' <' . clean_header_value(MAIL_FROM) . '>',
        'X-Mailer: JaydenWebsite/1.0',
    ];
    if ($replyTo && filter_var($replyTo, FILTER_VALIDATE_EMAIL)) {
        $headers[] = 'Reply-To: ' . clean_header_value($replyTo);
    }
    return implode("\r\n", $headers);
}

function email_table(array $rows): string
{
    $html = '<table style="width:100%;border-collapse:collapse;font-family:Arial,sans-serif;font-size:14px">';
    foreach ($rows as $label => $value) {
        if ($value === '') continue;
        $html .= '<tr>';
        $html .= '<td style="padding:10px;border:1px solid #dfe7ef;width:32%;font-weight:700;color:#0D47A1">' . e((string) $label) . '</td>';
        $html .= '<td style="padding:10px;border:1px solid #dfe7ef;white-space:pre-wrap">' . nl2br(e((string) $value)) . '</td>';
        $html .= '</tr>';
    }
    return $html . '</table>';
}

function send_site_mail(string $subject, array $rows, ?string $replyTo = null): bool
{
    $subject = clean_header_value($subject);
    $body = '<div style="max-width:720px;margin:auto;font-family:Arial,sans-serif;color:#1f2d3d">'
        . '<h2 style="color:#0D47A1;margin-bottom:4px">Jayden Website Enquiry</h2>'
        . '<p style="margin-top:0;color:#526273">Submitted from jaydencares.com</p>'
        . email_table($rows)
        . '<p style="font-size:12px;color:#6d7a86;margin-top:18px">This message was generated by the Jayden website. Reply only where a valid visitor email address is supplied.</p>'
        . '</div>';

    $encodedBody = rtrim(
        chunk_split(
            base64_encode($body),
            76,
            "\r\n"
        )
    );

    return mail(MAIL_TO, $subject, $encodedBody, mail_headers($replyTo));
}
